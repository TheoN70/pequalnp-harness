#!/usr/bin/env python3
"""rep_not_gen.py: "The n by n bipartite graph with mask M is represented on the one-a-side promise by an AND/OR/NOT
circuit of fan-in two with at most k gates" (∃ C, FanInTwo C ∧ C.size ≤ k ∧ Represents (fun u v : Fin n => (M : ℕ).testBit
(n * u.val + v.val)) C): circsat (NOT allowed) on the n*n promise rows, written as Erolaz's data-only proof
(L-meta-19538, open-goat/pequalnp-proofs; ~460 B): circuit, FanInTwo by simp, size by decide, Represents by decide +kernel.
Wires: left u = wire u, right v = wire n+v (circuit2lean's convention).

usage: sat-venv/bin/python -I rep_not_gen.py <lease.json> <out.lean> [--circuit '<json>']
exit 0 written; 3 other statement; 4 UNSAT (no such circuit: the unit is false); --demo regenerates L_meta_19538.
"""
import json, os, re, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.realpath(__file__)))
from gen_common import load_lease, write, die, OTHER, FALSE
import circuit2lean as c2l, circsat

PAT = re.compile(r"∃ C : PEqualNP\.CircuitLowerBounds\.Circuit, PEqualNP\.MetaComplexity\.FanInTwo C ∧ C\.size ≤ (\d+) ∧ "
                 r"PEqualNP\.Represents\.Represents \(fun u v : Fin (\d+) => \((\d+) : ℕ\)\.testBit \((\d+) \* u\.val \+ v\.val\)\) C")

def render(sid, st, c):
    gl = ", ".join("⟨.%s, [%s]⟩" % (op, ", ".join(map(str, a))) for op, a in c["gates"])
    return ("import PEqualNP.Defs\n\ntheorem PEqualNP.Outside.%s :\n    %s := by\n  refine ⟨⟨[%s], %d⟩, ?_, ?_, ?_⟩\n"
            "  · simp [PEqualNP.MetaComplexity.FanInTwo]\n  · decide\n  · decide +kernel\n") % (sid, st, gl, c["output"])

def main(a):
    g = load_lease(a[0]); st = g.statement.strip()
    m = PAT.fullmatch(st)
    if not m or m[2] != m[4]: die(OTHER, "not a signed one-a-side Represents statement")
    k, n, M = int(m[1]), int(m[2]), int(m[3])
    if "--circuit" in a: c = json.loads(a[a.index("--circuit") + 1])
    else:
        pts = c2l.one_a_side(n, n, M)
        c = circsat.solve(2 * n, k, sum(1 << r for r, v in pts if v), [r for r, _ in pts])
        if c is None: die(FALSE, "%s: UNSAT, no AND/OR/NOT circuit of <= %d gates" % (g.id, k))
    assert len(c["gates"]) <= k
    write(a[1], render(g.sid, st, c))

if __name__ == "__main__":
    if sys.argv[1:2] == ["--demo"]:
        import tempfile
        here = os.path.dirname(os.path.realpath(__file__))
        ref = subprocess.run(["git", "-C", os.path.join(here, "..", "..", "pequalnp-proofs"), "show",
                              "upstream/main:lean/PEqualNP/Outside/L_meta_19538.lean"], capture_output=True, text=True).stdout
        st = ref.split("L_meta_19538 :\n    ", 1)[1].split(" := by\n", 1)[0]
        d = tempfile.mkdtemp(); lp, op = os.path.join(d, "l.json"), os.path.join(d, "o.lean")
        json.dump({"gap": {"id": "L-meta-19538", "statement": st, "title": "", "file": "", "module": ""}}, open(lp, "w"))
        main([lp, op, "--circuit", json.dumps({"gates": [["or", [0, 4]], ["or", [3, 7]], ["not", [9]], ["and", [8, 10]]], "output": 11})])
        assert open(op).read() == ref, "19538 not regenerated"
        main([lp, op]); print("demo ok: 19538 regenerated byte for byte; SAT circuit written:", open(op).read().split("refine ")[1][:90])
    else: main(sys.argv[1:])
